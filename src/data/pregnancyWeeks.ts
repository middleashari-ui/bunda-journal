export const AVAILABLE_WEEKS = Array.from({ length: 36 }, (_, i) => i + 5); // Weeks 5 to 40

export function getWeekData(week: number): BabyWeekInfo {
  if (PREGNANCY_WEEKS_DATA[week]) {
    return PREGNANCY_WEEKS_DATA[week];
  }
  const trimester = week <= 13 ? 1 : week <= 27 ? 2 : 3;
  const month = Math.min(9, Math.ceil(week / 4.4));
  return {
    week,
    trimester,
    month,
    fruitEmoji: '🌱',
    fruitName: 'Buah Hati',
    lengthCm: `${(week * 1.25).toFixed(1)} cm`,
    weightGrams: `${Math.round(Math.pow(week, 2.1))} gram`,
    heartbeatBpm: '140 bpm',
    daysLeft: Math.max(0, (40 - week) * 7),
    quote: `Minggu ke-${week} perjalanan indahmu bertumbuh dalam rahim bunda...`,
    highlights: [
      'Organ dan jaringan tubuh terus mematangkan fungsinya',
      'Nutrisi dan doa bunda menjadi pondasi terbaik si kecil',
      'Detak jantung terpantau sehat dan berirama damai'
    ]
  };
}
